import assert from "node:assert/strict";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { posts } from "../content/blog/posts.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const site = resolve(root, "site");
const home = readFileSync(resolve(site, "index.html"), "utf8");
const base = home.match(/<link rel="canonical" href="([^"]+)"/)?.[1];
assert(base && base.endsWith("/"), "Homepage needs a canonical directory URL");
assert.equal(new URL(base).protocol, "https:");
const check = process.argv.includes("--check");
const esc = (value) => String(value)
  .replaceAll("&", "&amp;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;")
  .replaceAll('"', "&quot;")
  .replaceAll("'", "&apos;");
const markdown = (value) => String(value)
  .replaceAll(/\s+/g, " ")
  .replaceAll(/([\\`*_{}\[\]<>])/g, "\\$1");
const ordered = [...posts].sort((a, b) => b.published.localeCompare(a.published));
const pages = [{ path: "" }, { path: "blog/" }];
const slugs = new Set();
for (const post of ordered) {
  assert(/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(post.slug), "Invalid article slug");
  assert(!slugs.has(post.slug), `Duplicate article: ${post.slug}`);
  slugs.add(post.slug);
  assert(/^\d{4}-\d{2}-\d{2}$/.test(post.updated)
    && !Number.isNaN(Date.parse(post.updated))
    && new Date(post.updated).toISOString().slice(0, 10) === post.updated,
  `Invalid modification date: ${post.slug}`);
  pages.push({ path: `blog/${post.slug}/`, lastmod: post.updated });
}
// Deliberate public-page allowlist: never discover the noindex business plan
// by recursively scanning the publishing directory.
for (const page of pages) {
  const html = readFileSync(resolve(site, page.path, "index.html"), "utf8");
  assert(!/<meta\b[^>]*\bcontent=["'][^"']*noindex/i.test(html),
    `Cannot advertise a noindex page: ${page.path}`);
  assert(html.includes(`<link rel="canonical" href="${base}${page.path}"`),
    `Canonical URL mismatch: ${page.path}`);
}
for (const anchor of ["services", "areas", "about", "contact"]) {
  assert(home.includes(`id="${anchor}"`), `Missing homepage anchor: ${anchor}`);
}

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-discovery.mjs. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map(({ path, lastmod }) => `  <url><loc>${esc(`${base}${path}`)}</loc>${lastmod ? `<lastmod>${lastmod}</lastmod>` : ""}</url>`).join("\n")}
</urlset>
`;
const llms = `# Arin Handyman and Contracting

> Home repairs and renovations across Halton and the Greater Toronto Area, Ontario, Canada. The site includes researched homeowner guides.

The service categories shown are handyman repairs, drywall and finishing, painting and refreshes, carpentry and details, flooring and tile, kitchen and bath updates, and basement framing and drywall. Listed communities include Milton, Mississauga, Oakville, Brampton, Burlington, and Toronto.

Project enquiries: (416) 455-0606 or arin@youssefian.com. The website displays these contact details with tap-to-call and email links; it has no contact form, booking, or payment system. The site does not establish verified trade licences, credentials, reviews, prices, or guarantees.

Home notes articles provide general planning guidance, with numbered source citations and deliberate publication, update, and source-check dates. Read each article's qualifications and original sources before relying on guidance for a specific property or municipality.

## Business information

- [Homepage](${base}): Business overview and project enquiries.
- [Services](${base}#services): Descriptions of the service categories shown on the site.
- [Service area](${base}#areas): Halton and Greater Toronto Area communities listed on the site.
- [About Arin](${base}#about): The site's business introduction.
- [Contact](${base}#contact): Business phone number, email address, and details to include in an enquiry.

## Homeowner guides

- [Home notes](${base}blog/): Index of all researched guides.
${ordered.map((post) => `- [${markdown(post.title)}](${base}blog/${post.slug}/): ${markdown(post.excerpt)}`).join("\n")}

## Optional

- [XML sitemap](${base}sitemap.xml): Canonical public pages for search discovery.
`;
const robots = `# Generated by scripts/build-discovery.mjs.
# Served at ${new URL("/robots.txt", base).href}.
# Keep noindex pages crawlable so crawlers can read their noindex metadata.
User-agent: *
Allow: ${new URL(base).pathname}

Sitemap: ${base}sitemap.xml
`;
const outputs = new Map([
  ["sitemap.xml", sitemap],
  ["llms.txt", llms],
  ["robots.txt", robots],
]);
const stale = [];
for (const [name, expected] of outputs) {
  const path = resolve(site, name);
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8").replaceAll("\r\n", "\n") !== expected)
      stale.push(name);
  } else {
    writeFileSync(path, expected);
  }
}
if (stale.length) {
  console.error(`Discovery output is out of date: ${stale.join(", ")}.\nRun: node scripts/build-discovery.mjs`);
  process.exitCode = 1;
} else {
  console.log(`${check ? "Verified" : "Generated"} sitemap (${pages.length} pages), llms.txt, and robots.txt.`);
}
