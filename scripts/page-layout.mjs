import assert from "node:assert/strict";
import { siteConfig, robots } from "../content/site-config.mjs";

export const base = siteConfig.baseUrl;
export const brand = siteConfig.brand;
assert(
  new URL(base).protocol === "https:" && base.endsWith("/"),
  "Use an absolute HTTPS base URL ending in /.",
);
const socialImage = `${base}assets/social-preview-v2.jpg`;
const socialImageAlt = `${brand} — Home repairs and renovations across Halton and the Greater Toronto Area, with AI-generated concept carpentry imagery.`;
export const esc = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
export const arrow =
  '<svg class="icon" aria-hidden="true" focusable="false"><use href="#i-diagonal"/></svg>';

export function metadata({ title, description, canonical, post, schema }) {
  return `<title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}">
  <meta name="robots" content="${robots}">
  <link rel="canonical" href="${esc(canonical)}">
  <meta property="og:type" content="${post ? "article" : "website"}"><meta property="og:locale" content="en_CA"><meta property="og:site_name" content="${esc(brand)}">
  <meta property="og:title" content="${esc(title)}"><meta property="og:description" content="${esc(description)}"><meta property="og:url" content="${esc(canonical)}">
  <meta property="og:image" content="${socialImage}"><meta property="og:image:secure_url" content="${socialImage}"><meta property="og:image:type" content="image/jpeg"><meta property="og:image:width" content="1200"><meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="${esc(socialImageAlt)}">
  <meta name="twitter:card" content="summary_large_image"><meta name="twitter:title" content="${esc(title)}"><meta name="twitter:description" content="${esc(description)}"><meta name="twitter:image" content="${socialImage}"><meta name="twitter:image:alt" content="${esc(socialImageAlt)}">${
    post
      ? `
  <meta property="article:published_time" content="${post.published}"><meta property="article:modified_time" content="${post.updated}">`
      : ""
  }${
    schema
      ? `
  <script type="application/ld+json">${JSON.stringify(schema).replaceAll("<", "\\u003c")}</script>`
      : ""
  }`;
}

export function configureHomepage(home) {
  const marker = /<!-- SEO:START -->[\s\S]*?<!-- SEO:END -->/;
  assert(marker.test(home), "Homepage SEO markers are missing");
  return home.replace(
    marker,
    `<!-- SEO:START -->\n  ${metadata({ title: siteConfig.homeTitle, description: siteConfig.homeDescription, canonical: base })}\n  <!-- SEO:END -->`,
  );
}

function sharedLinks(markup, prefix, current) {
  return markup.replace(
    /(<a\b[^>]*\bhref=")([^"]+)(")/g,
    (match, before, href, after) => {
      const rewritten = /class="back-top"/.test(before)
        ? "#main"
        : href.startsWith("#")
          ? `${prefix}index.html${href}`
          : /^(https?:|mailto:|tel:)/.test(href)
            ? href
            : `${prefix}${href}`;
      return `${before}${rewritten}${after}${current === href ? ' aria-current="page"' : ""}`;
    },
  );
}

export function createLayout(home) {
  const header = home.match(/<div class="utility-bar">[\s\S]*?<\/header>/)?.[0];
  const footer = home.match(
    /<footer class="site-footer">[\s\S]*?<\/footer>/,
  )?.[0];
  const icons = home.match(
    /<svg\b[^>]*class="icon-definitions"[^>]*>[\s\S]*?<\/svg>/,
  )?.[0];
  const stylesheet = home.match(/href="(styles\.css[^"]*)"/)?.[1];
  const blogStylesheet = home.match(/href="(blog\/blog\.css[^"]*)"/)?.[1];
  const script = home.match(/src="(script\.js[^"]*)"/)?.[1];
  assert(
    header && footer && icons && stylesheet && blogStylesheet && script,
    "Could not find shared homepage layout",
  );
  return function layout({
    title,
    description,
    canonical,
    prefix,
    main,
    post,
    schema,
    kind = "blog",
  }) {
    return `<!doctype html>
<!-- Generated by scripts/build-${kind === "blog" ? "blog" : "services"}.mjs. Edit content/${kind === "blog" ? "blog/posts" : "services"}.mjs, not this file. -->
<html lang="en-CA" prefix="og: https://ogp.me/ns#">
<head>
  <meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="theme-color" content="#f7f4ed">
  ${metadata({ title: `${title} | ${brand}`, description, canonical, post, schema })}
  <link rel="icon" href="${prefix}assets/favicon.svg" type="image/svg+xml"><link rel="stylesheet" href="${prefix}${stylesheet}"><link rel="stylesheet" href="${prefix}${blogStylesheet}"><script src="${prefix}${script}" defer></script>
</head>
<body class="${kind}-page"><a class="skip-link" href="#main">Skip to content</a>
${icons}
${sharedLinks(header, prefix, kind === "blog" ? "blog/" : null)}
<main id="main">${main}</main>
${sharedLinks(footer, prefix)}
</body></html>
`;
  };
}
